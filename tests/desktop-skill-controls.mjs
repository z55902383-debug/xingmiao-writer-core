import { _electron as electron, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createServer } from 'node:http';
const parent = resolve('test-results/skill-controls');
await mkdir(parent, { recursive: true });
const output = await mkdtemp(resolve(parent, 'run-'));
const requests = [];
const server = createServer(async (req, res) => {
  let raw = ''; for await (const part of req) raw += part;
  const value = JSON.parse(raw); requests.push(value);
  res.writeHead(200, { 'content-type': 'text/event-stream' });
  res.end('data: ' + JSON.stringify({ choices: [{ delta: { content: '测试正文：她接过钥匙，决定离开。' }, finish_reason: 'stop' }] }) + '\n\ndata: [DONE]\n\n');
});
await new Promise(done => server.listen(0, '127.0.0.1', done));
const env = { ...process.env, XM_TEST: '1', XM_DATA_DIR: resolve(output, 'data') };
delete env.ELECTRON_RUN_AS_NODE; delete env.XM_DEV_URL;
let app;
try {
  app = await electron.launch({ args: ['.'], env });
  const page = await app.firstWindow();
  await page.setViewportSize({ width: 1460, height: 900 });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await expect(page.getByRole('button', { name: '模型与设置', exact: true })).toBeVisible();
  const call = (action, data = {}) => page.evaluate(async ({ action, data }) => {
    const result = await window.xingmiao.invoke(action, data);
    if (!result.ok) throw Error(result.error); return result.data;
  }, { action, data });
  await call('skill:save', { name: '测试默认', body: 'DEFAULT-TEST-BODY', description: '全局默认用于正文', enabled: true, tasks: ['write'] });
  await call('skill:save', { name: '测试本次', body: 'CHOSEN-TEST-BODY', description: '仅本次使用的对白方法', enabled: false, tasks: ['write'] });
  await call('skill:save', { name: '测试规划', body: 'OUTLINE-TEST-BODY', enabled: true, tasks: ['outline'] });
  await page.getByRole('button', { name: '创建第一部作品' }).click();
  await page.getByLabel('书名 *', { exact: true }).fill('Skill 界面测试');
  await page.getByRole('button', { name: '创建作品', exact: true }).click();
  await expect(page.getByRole('textbox', { name: '章节正文' })).toBeVisible();
  await page.getByRole('button', { name: '模型与设置', exact: true }).click();
  await page.getByLabel('接口地址', { exact: true }).fill(`http://127.0.0.1:${server.address().port}/v1`);
  await page.getByLabel('模型名称', { exact: true }).fill('fixture-model');
  await page.getByLabel('API 密钥', { exact: true }).fill('fixture-no-real-key');
  await page.getByRole('button', { name: '保存并测试连接' }).click();
  await expect(page.getByText(/连接成功 ·/)).toBeVisible();
  await page.getByRole('button', { name: '关闭弹窗' }).click();
  await page.getByRole('tab', { name: '创作正文', exact: true }).click();
  await page.getByRole('button', { name: '按大纲写正文', exact: true }).click();
  await page.getByRole('button', { name: '选择风格并核对参考资料' }).click();
  const picker = page.getByRole('region', { name: '本次写作 Skill' });
  await expect(picker.getByRole('checkbox', { name: '本次使用 测试默认', exact: true })).toBeChecked();
  await expect(picker.getByRole('checkbox', { name: '本次使用 测试规划', exact: true })).toHaveCount(0);
  await picker.getByRole('button', { name: '本次不使用 Skill', exact: true }).click();
  await picker.getByRole('checkbox', { name: '本次使用 测试本次', exact: true }).click();
  await expect(picker.getByRole('checkbox', { name: '本次使用 测试默认', exact: true })).not.toBeChecked();
  await picker.getByLabel('搜索 Skill 名称或说明', { exact: true }).fill('本次');
  await expect(picker.locator('.writing-choice')).toHaveCount(1);
  await page.screenshot({ path: resolve(output, 'desktop-dark.png') });
  await page.getByRole('button', { name: '切换到浅色模式', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await expect.poll(() => page.evaluate(() => document.documentElement.dataset.themeReveal || '')).toBe('');
  await page.screenshot({ path: resolve(output, 'desktop-light.png'), animations: 'disabled' });
  await page.getByRole('button', { name: '切换到深色模式', exact: true }).click();
  await expect.poll(() => page.evaluate(() => document.documentElement.dataset.themeReveal || '')).toBe('');
  await page.getByRole('tab', { name: '创作正文', exact: true }).click();
  await page.getByRole('button', { name: '按大纲写正文', exact: true }).click();
  await page.getByRole('button', { name: '开始生成', exact: true }).click();
  await expect(page.locator('.candidate-text')).toContainText('测试正文');
  await writeFile(resolve(output, 'requests.json'), JSON.stringify(requests, null, 2));
  const prompt = requests.slice(1).map(request => request.messages.map(message => message.content).join('\n')).join('\n');
  assert.ok(prompt.includes('CHOSEN-TEST-BODY'));
  assert.ok(!prompt.includes('DEFAULT-TEST-BODY') && !prompt.includes('OUTLINE-TEST-BODY'));
  assert.equal((await call('skills:list')).find(skill => skill.name === '测试本次').enabled, false);
  await picker.getByRole('button', { name: '恢复默认启用', exact: true }).click();
  await picker.getByRole('button', { name: '管理写作 Skill', exact: true }).click();
  await expect(page.getByLabel('筛选 Skill 状态', { exact: true })).toBeVisible();
  await page.getByLabel('搜索 Skill', { exact: true }).fill('测试');
  await page.getByLabel('筛选 Skill 状态', { exact: true }).selectOption('enabled');
  await page.getByLabel('筛选适用任务', { exact: true }).selectOption('write');
  await expect(page.locator('.skill-row')).toHaveCount(1);
  await page.locator('.skill-row').getByText('查看完整指令', { exact: true }).click();
  await expect(page.locator('.skill-library-content .writing-profile-text')).toContainText('DEFAULT-TEST-BODY');
  await page.screenshot({ path: resolve(output, 'manager.png') });
  await page.getByRole('button', { name: '关闭弹窗' }).click();
  await page.setViewportSize({ width: 1024, height: 768 });
  const drawer = page.getByRole('button', { name: '打开写作助手', exact: true });
  if (await drawer.isVisible()) await drawer.click();
  await page.getByRole('button', { name: '选择风格并核对参考资料' }).click();
  await page.screenshot({ path: resolve(output, 'narrow-dark.png') });
  const bounds = await picker.boundingBox();
  assert.ok(bounds && bounds.x >= 0 && bounds.x + bounds.width <= 1025);
  assert.deepEqual(errors, []);
  await writeFile(resolve(output, 'report.json'), JSON.stringify({ passed: true, actualProviderPromptScoped: true, globalDefaultsPreserved: true, taskFiltered: true, managerFilters: true, narrowFits: true, errors }, null, 2));
  console.log('Skill controls desktop checks passed: ' + output);
} finally {
  if (app) await app.close().catch(() => {});
  await new Promise(done => server.close(done));
}
