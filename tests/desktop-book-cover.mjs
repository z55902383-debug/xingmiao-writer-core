import { _electron as electron, expect } from '@playwright/test';
import { mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import assert from 'node:assert/strict';
const root = resolve('test-results/book-cover'); await mkdir(root, { recursive: true });
const output = await mkdtemp(join(root, 'run-'));
const env = { ...process.env, XM_TEST: '1', XM_DATA_DIR: join(output, 'data') };
delete env.ELECTRON_RUN_AS_NODE; delete env.XM_DEV_URL;
const app = await electron.launch({ args: ['.'], env });
try {
  const page = await app.firstWindow(); const errors = []; page.on('pageerror', e => errors.push(e.message));
  const call = (action, args = {}) => page.evaluate(async ({ action, args }) => {
    const r = await window.xingmiao.invoke(action, args); if (!r.ok) throw Error(r.error); return r.data;
  }, { action, args });
  await expect(page.getByRole('heading', { name: '我的书架', exact: true })).toBeVisible();
  const book = await call('book:create', { title: '雨夜的信件', genre: '悬疑' });
  await page.reload(); await expect(page.locator('.book-card')).toHaveCount(1);
  const fixture = await page.evaluate(() => {
    const c = document.createElement('canvas'); c.width = 600; c.height = 800;
    const x = c.getContext('2d'); x.fillStyle = '#243950'; x.fillRect(0, 0, 600, 800);
    x.fillStyle = '#e8dfcb'; x.font = '48px serif'; x.fillText('雨夜的信件', 60, 160);
    x.fillStyle = '#ae8e67'; x.fillRect(70, 310, 460, 5); return c.toDataURL('image/png').split(',')[1];
  });
  const open = async () => { await page.locator('.book-cover-slot').hover(); await page.getByRole('button', { name: '管理封面：雨夜的信件', exact: true }).click(); };
  await open();
  const file = page.getByLabel('选择封面图片', { exact: true });
  await file.setInputFiles({ name: 'bad.txt', mimeType: 'text/plain', buffer: Buffer.from('invalid') });
  await expect(page.getByRole('alert')).toContainText('请选择 JPG');
  await file.setInputFiles({ name: 'cover.png', mimeType: 'image/png', buffer: Buffer.from(fixture, 'base64') });
  await expect(page.locator('.cover-editor-preview img')).toBeVisible();
  await page.getByRole('slider', { name: '缩放', exact: true }).fill('1.4');
  await page.getByRole('slider', { name: '水平位置', exact: true }).fill('30');
  await page.getByRole('slider', { name: '垂直位置', exact: true }).fill('70');
  await page.screenshot({ path: join(output, 'editor.png') });
  await page.getByRole('button', { name: '保存封面', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const saved = (await call('book:get', { id: book.id })).cover;
  assert.equal(saved.zoom, 1.4); assert.equal(saved.x, 30); assert.equal(saved.y, 70);
  const backupPath = join(output, 'cover-backup.json');
  await app.evaluate(({ dialog }, path) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: path }); dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, backupPath);
  await call('backup:save');
  await page.reload(); await expect(page.locator('.book-card .book-cover-image')).toBeVisible();
  const rect = await page.locator('.book-card .book-cover').boundingBox(); assert.ok(Math.abs(rect.width / rect.height - .75) < .01);
  await open(); await page.getByRole('button', { name: '删除封面', exact: true }).click();
  await page.getByRole('button', { name: '取消', exact: true }).click();
  assert.deepEqual((await call('book:get', { id: book.id })).cover, saved);
  await open(); await page.getByRole('button', { name: '重置位置', exact: true }).click();
  await expect(page.getByRole('slider', { name: '缩放', exact: true })).toHaveValue('1');
  await page.getByRole('button', { name: '保存封面', exact: true }).click();
  await page.screenshot({ path: join(output, 'shelf.png') });
  await open(); await page.getByRole('button', { name: '删除封面', exact: true }).click();
  await page.getByRole('button', { name: '保存封面', exact: true }).click();
  await expect(page.locator('.book-card .book-cover-image')).toHaveCount(0);
  assert.equal((await call('book:get', { id: book.id })).cover, null);
  await call('backup:restore');
  const restored = (await call('books:list')).find(b => b.id !== book.id);
  assert.deepEqual(restored.cover, saved);
  assert.deepEqual(errors, []);
  await writeFile(join(output, 'report.json'), JSON.stringify({ status: 'passed', checks: ['upload', 'invalid file', 'crop', 'reload persistence', '3:4 ratio', 'cancel deletion', 'reset', 'delete'], errors }, null, 2));
  console.log('Book cover acceptance passed: ' + output);
} finally { await app.evaluate(({ app }) => app.exit(0)).catch(() => {}); }
